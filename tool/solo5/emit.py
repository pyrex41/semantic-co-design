"""Write what the C driver is compiled with, from a node manifest.

    python3 -m tool.solo5.emit <node.json> <directory>
    python3 -m tool.solo5.emit --all <directory>     every image of scenarios.py
    python3 -m tool.solo5.emit --cluster <directory> every image of cluster_scenarios.py

    node.c         the compiled step: the same text `tool.compile.build` compiles for the
                     simulator (same specializer, same template), with its SHA-256 beside it
    node_tables.h    the manifest as C tables: widths, tag codes, roles, leaf kinds
    manifest.json    the Solo5 application manifest (which devices the image declares)
    driver.c         a copy of the driver, edited when a mutant is asked for, with its
                     SHA-256 beside it

Nothing here needs a C compiler or shen-jit, so the same step runs in a Nix build sandbox.
"""
import hashlib
import json
from pathlib import Path
import sys

from ..compile import c_source, lower, specialize, specialize_init
from ..schema import Schema

HERE = Path(__file__).parent
DISK, NET = "disk", "net"          # device names in the Solo5 manifest
ROLES = ("none", "request", "recv", "disk-ack", "disk-read-result", "restart", "timer", "clock",
         "output", "send", "disk-write", "disk-read", "timer-set", "timer-cancel", "clock-read")
NETWORK = ("request", "output", "send", "recv")     # the roles that need the network device
LEAF = {"num": "n", "sym": "s", "bool": "b"}


class EmitError(ValueError):
    pass


def leaves(shape):
    return LEAF[shape] if isinstance(shape, str) else "".join(map(leaves, shape))


def row_width(schema):
    """How many integers a disk row holds, or None when the node has no disk."""
    widths = {kind.width - 2 for kind in schema.effects.values() if kind.role == "disk-write"}
    if "disk-read-result" in schema.roles:
        widths.add(schema.roles["disk-read-result"].width - 3)
    if len(widths) > 1:
        raise EmitError(f"disk rows of different widths {sorted(widths)}: the driver stores "
                        "one row layout per device")
    return widths.pop() if widths else None


def tables(schema):
    """node_tables.h: the manifest, and nothing else, as C constants."""
    for kind in schema.effects.values():
        # The driver puts the sender where the destination was, so that field is a node
        # number on both sides. (The schema already requires `deliver` to name a recv
        # event with the same fields.)
        if kind.role == "send" and (not kind.fields or kind.fields[0] != "num"):
            raise EmitError(f"{kind.tag}: the first field of a send is the destination node and "
                            "must be a num; tool/solo5 cannot address anything else")
    for kind in schema.events.values():
        if kind.role == "recv" and (not kind.fields or kind.fields[0] != "num"):
            raise EmitError(f"{kind.tag}: the first field of a recv is the sending node and "
                            "must be a num")
    macro = lambda role: "R_" + role.upper().replace("-", "_")

    def table(name, kinds):
        rows = [f'    {{{schema.code[k.tag]}, {macro(k.role)}, {k.width}, "{leaves(k.fields)}", '
                f'"{k.tag}", {schema.code[k.deliver] if k.role == "send" else 0}}},'
                for k in kinds.values()]
        return [f"static const struct kind {name}[] = {{", *rows, "};"]

    role_code = lambda role: schema.code[schema.roles[role].tag] if role in schema.roles else 0
    used = {kind.role for kind in [*schema.events.values(), *schema.effects.values()]}
    width = row_width(schema)
    lines = [
        "/* Generated by tool/solo5/emit.py from the node manifest. Do not edit. */",
        f'#define NODE_NAME "{schema.name}"',
        "enum role { " + ", ".join(macro(role) for role in ROLES) + " };",
        "/* `deliver`: for a send effect, the tag code of the event its receiver handles. */",
        "struct kind { int64_t code; int role; int width; const char *leaves; const char *tag; "
        "int64_t deliver; };",
        f"enum {{ STATE_WIDTH = {schema.state_width}, EVENT_WIDTH = {schema.event_width}, "
        f"EFFECT_WIDTH = {schema.effect_width},",
        f"       INPUT_WIDTH = {schema.input_width}, OUTPUT_CAPACITY = {schema.output_capacity}, "
        f"MAX_EFFECTS = {schema.max_effects},",
        f"       SYMBOLS = {len(schema.symbols)}, NEVENTS = {len(schema.events)}, "
        f"NEFFECTS = {len(schema.effects)}, ROW_WIDTH = {width or 0},",
        f"       USES_DISK = {int(width is not None)}, "
        f"USES_NET = {int(bool(used & set(NETWORK)))} }};",
        "/* The tag code of the event with each role; 0 when the manifest has none. */",
        f"enum {{ EV_RESTART = {role_code('restart')}, EV_DISK_ACK = {role_code('disk-ack')}, "
        f"EV_DISK_READ_RESULT = {role_code('disk-read-result')},",
        f"       EV_TIMER = {role_code('timer')}, EV_CLOCK = {role_code('clock')} }};",
        *table("EVENTS", schema.events), *table("EFFECTS", schema.effects),
        f'static const char *const STATE_LEAVES = "{leaves(schema.state)}";',
    ]
    return "\n".join(lines) + "\n"


def solo5_manifest(schema):
    devices = []
    if row_width(schema) is not None:
        devices.append({"name": DISK, "type": "BLOCK_BASIC"})
    if any(k.role in NETWORK for k in [*schema.events.values(), *schema.effects.values()]):
        devices.append({"name": NET, "type": "NET_BASIC"})
    return {"type": "solo5.manifest", "version": 1, "devices": devices}


def node_c(schema, source=None):
    """The C text of the compiled step, exactly as `tool.compile.build` writes it."""
    tree, slots, _ = specialize(schema, source)
    init_tree, init_slots = specialize_init(schema, source)
    _, body = lower(tree, slots)
    _, init_body = lower(init_tree, init_slots)
    return c_source(body, slots, init_body, init_slots)


def driver_c(mutant=None):
    text = (HERE / "driver.c").read_text()
    if mutant is None:
        return text
    from .mutants import DRIVERS
    from .cluster_scenarios import DRIVERS as CLUSTER
    edit = {**DRIVERS, **CLUSTER}[mutant]
    if text.count(edit["old"]) != 1:
        raise EmitError(f"mutation site of {mutant} is not unique")
    return text.replace(edit["old"], edit["new"])


def emit(schema, directory, *, source=None, mutant=None):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    code = node_c(schema, source)
    (directory / "node.c").write_text(code)
    digest = hashlib.sha256(code.encode()).hexdigest()
    (directory / "node.c.sha256").write_text(digest + "\n")
    (directory / "node_tables.h").write_text(tables(schema))
    (directory / "manifest.json").write_text(json.dumps(solo5_manifest(schema), indent=2) + "\n")
    driver = driver_c(mutant)
    (directory / "driver.c").write_text(driver)
    (directory / "driver.c.sha256").write_text(hashlib.sha256(driver.encode()).hexdigest() + "\n")
    return digest


def emit_all(directory, names=None):
    """Every image of tool/solo5/scenarios.py, each into its own subdirectory.
    Returns {image name: SHA-256 of its node.c}."""
    from .scenarios import IMAGES, manifest, source
    digests = {}
    for name, image in IMAGES.items():
        if names is None or name in names:
            digests[name] = emit(Schema(manifest(image)), Path(directory) / name,
                                 source=source(image), mutant=image.get("driver"))
    return digests


def emit_cluster(directory):
    """Every image of tool/solo5/cluster_scenarios.py. Returns {image name: SHA-256 of node.c}."""
    from .cluster_scenarios import IMAGES, manifest, source
    return {name: emit(Schema(manifest(image)), Path(directory) / name, source=source(image),
                       mutant=image.get("driver")) for name, image in IMAGES.items()}


def main(argv):
    if len(argv) == 2 and argv[0] == "--cluster":
        digests = emit_cluster(argv[1])
        (Path(argv[1]) / "node.c.sha256.json").write_text(json.dumps(digests, sort_keys=True) + "\n")
        drivers = {name: (Path(argv[1]) / name / "driver.c.sha256").read_text().strip()
                   for name in digests}
        (Path(argv[1]) / "driver.c.sha256.json").write_text(json.dumps(drivers, sort_keys=True) + "\n")
        return 0
    if len(argv) == 2 and argv[0] == "--all":
        digests = emit_all(argv[1])
        (Path(argv[1]) / "node.c.sha256.json").write_text(json.dumps(digests, sort_keys=True) + "\n")
        drivers = {name: (Path(argv[1]) / name / "driver.c.sha256").read_text().strip()
                   for name in digests}
        (Path(argv[1]) / "driver.c.sha256.json").write_text(json.dumps(drivers, sort_keys=True) + "\n")
        return 0
    if len(argv) != 2:
        print(__doc__)
        return 2
    print(emit(Schema(argv[0]), argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
